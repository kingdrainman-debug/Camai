import { DEFAULTS, Settings, diffFromDefaults, sanitize } from './params';
import { EMPTY_TIMELINE, Timeline, countKeyframes, sanitizeTimeline } from './timeline';

export interface Preset {
  id: string;
  name: string;
  description: string;
  settings: Settings;
}

function preset(
  id: string,
  name: string,
  description: string,
  overrides: Record<string, number | boolean | string>,
): Preset {
  return { id, name, description, settings: sanitize(overrides, DEFAULTS) };
}

